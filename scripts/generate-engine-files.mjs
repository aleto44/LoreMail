/**
 * Generates apps/worker/src/lib/engine-files.js from the local packages/gm-engine source.
 * Run with: node scripts/generate-engine-files.mjs
 * Re-run whenever packages/gm-engine source changes.
 */
import { readFile, writeFile, readdir } from 'fs/promises';
import path from 'path';
import { fileURLToPath } from 'url';
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const ENGINE_ROOT = path.join(ROOT, 'packages/gm-engine');
const OUT_FILE = path.join(ROOT, 'apps/worker/src/lib/engine-files.js');
async function main() {
  const files = {};
  // index.js
  files['engine/index.js'] = await readFile(path.join(ENGINE_ROOT, 'index.js'), 'utf8');
  // src/*.js
  const srcDir = path.join(ENGINE_ROOT, 'src');
  const srcFiles = (await readdir(srcDir)).filter(f => f.endsWith('.js'));
  for (const name of srcFiles) {
    files[`engine/src/${name}`] = await readFile(path.join(srcDir, name), 'utf8');
  }
  const entries = Object.entries(files)
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`)
    .join(',\n');
  const output = `// AUTO-GENERATED by scripts/generate-engine-files.mjs\n// Do not edit manually. Re-run the script after changing packages/gm-engine.\nexport const engineFiles = {\n${entries}\n};\n`;
  await writeFile(OUT_FILE, output, 'utf8');
  console.log('Written ' + Object.keys(files).length + ' files to ' + OUT_FILE);
}
main().catch(e => { console.error(e); process.exit(1); });
